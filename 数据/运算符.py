"""2. 赋值运算符
将值（或表达式的结果）保存到变量中的运算符，把右边的值和变量计算后赋给左边
=,+=,*=,/=,%/=,//=,**=
"""
num = 100
num *= 3
print(num)
num /= 8
print(num)
num %= 8
print(num)
num //= 8
print(num)

"""3. 比较运算符 也称为关系运算符，比较两个值之间的关系，会计算运算符两边的表达式，然后返回一个布尔值作为结果，成立还是不成立，True or False
等于==，不等于！=，大于>，大于等于>=，小于<，小于等于<=
"""

print("5 > 4",5 > 4)
print("5 < 4",5 < 4)
# 判断一个数是否为偶数
print("5是偶数",5 % 2 == 0)
print("5是奇数",5 % 2 == 1)

"""4. 逻辑运算符 连接多个条件（布尔）表达式（真或假），返回一个最终布尔结果
与and（同时为True才为True），或or（任一为True就是True），非/取反not（True变False，False变True）
"""
# 获取键盘输入，判断这个数是否在10到20之间
A = int(input("请输入一个整数"))
print("这个数在10到20之间",A > 10 and A < 20)

# 获取键盘输入，判断这个数是否不在10到20之间
A = int(input("请输入一个整数"))
print("这个数不在10到20之间",A < 10 or A > 20)


"""字面量决定数据如何写，变量决定数据怎么存储
字面量-直接书写的固定值（数据）
字面量类型：1.数字类型，整数int（包含正负）小数float（包含正负）
2.布尔（bool）：真假，True，False（注意首字母大写），分别被记录为1和0
3.字符串str：文本类型，必须要用双引号引起来
4.空值NoneType；空值，None
5.数据容器：存储多想数据的容器，列表/元组/集合/字典
"""
from collections.abc import async_generator

print(3.14) # float
print(True) # bool 注意首字母必须大写
print(False) #bool
print("hello") #str

print(None) # NoneType注意括号都得使用英文，否则会报错
print(True+2)
print(True-1)

# 字符串的定义
# 1. 双引号定义
s1 = "hello"
# 2. 单引号定义
s2 = 'it\'s a world'
# 3. 三引号定义多行字符串(3个双引号）
# 转义字符
# \'表示单引号
# \"表示双引号
# \n表示换行
# \t表示增加一个制表位tab的大小
s3 ="""
\t123
    344  1234
    123"""
print(s1)
print(s2)
print(s3)

# 字符串拼接
# 1.字符串直接串联
sl = "123""4556"
print(sl)
# 2.用加号拼接（加号只能拼接字符串,非字符串需要转化为字符串)
s1 = "人生苦短"
age = 55
s2 = "我用python"
# str（变量）将变量转为字符串
print("吉多 范罗苏姆" + str(age) + "岁时说：" + s1 + ","+s2)

# 字符串的格式化
# 1.通过占位符（%s会把变量变为字符串，%d只接受十进制整数）的形式完成字符串和变量的快速拼接
s1 = "123"
print("大家好，我是%s，今年%s岁欢迎大家进入课程学习" % (s1,age))
# 2. 通过f“内容{变量/表达式}”的形式完成快速格式化——推荐
print(f"大家好，我是{s1}，今年{age}岁欢迎大家进入课程学习")